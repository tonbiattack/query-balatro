/**
 * アンティ1〜8の目標チップと Boss 割り当て。
 *
 * 設計方針:
 * - 目標値は「1ブラインド＝プレイ4回」で割った1手あたりの要求が、
 *   序盤は易しく、終盤は役とジョーカーの噛み合わせを要求する形で上がる
 * - 伸び率は約1.5〜1.6倍/アンティ。急に跳ねる段を作らない（一直線の坂にしない）
 * - Boss は「断片の組み方を変えさせる」ものを後半に置く
 * - 数値はここに集約する。調整はこのファイルだけで完結させる
 */

import type { AnteConfig } from "../types.ts";

/**
 * アンティ1〜8の設定。
 *
 * ## 数値の根拠（実測に基づく）
 *
 * 1ブラインドはプレイ4回。貪欲AI（手札8枚から最大5枚の全218通りを毎手総当たり＋
 * ディスカード活用＋ジョーカー選択）で40ランを回し、
 * **ブラインドごとに「4手全力で出せるスコア」の中央値**を実測した:
 *
 *   a1s 2,748 / a1b 5,799 / a2s 6,030 / a2b 7,858
 *   a3s 7,660 / a3b 12,636 / a4s 11,365 / a4b 16,629
 *   a5s 13,617 / a5b 22,125 / a6s 18,540 / a6b 27,981
 *   a7s 25,123 / a7b 28,133
 *
 * 目標は「実測中央値の約65%」を出発点に、`npm run balance` の勝率が
 * 30%前後になるよう微調整した。このAIは**人間より強い**
 * （毎手218通りを総当たりできる）ので、30%は人間の初見には十分な挑戦になる。
 *
 * ## 理論上限（1手あたり）
 *
 * 全5ジョーカー所持時の1手の理論最大は **13,728**（`chips 528 × mult 26`）。
 * 1ブラインド（4手）の上限は約 54,912。
 * 目標はこれを超えない範囲に置く。超えると「引いた手札の運」でしか突破できなくなる。
 *
 * ## 開始ジョーカーを1つ持たせる理由
 *
 * ジョーカーはスコアの伸びを担う中核で、0個→1個でスコアが約2.5倍になる。
 * 開始時に0個だと、最初のジョーカーを獲得した瞬間（アンティ1 Boss 突破後）に
 * 目標値が跳ね、**そこだけが壁**になる。
 * 開始時から1つ持たせることで曲線が滑らかになり、
 * さらに「ジョーカーでスコアが伸びる」という本作の核を最初の1手から体験できる。
 *
 * ## Boss 妨害の割り当て方針
 *
 * `zeroOnDuplicate`（重複行でスコア0）は重複行を禁じるため使える断片が減り、
 * 実測でもスコアが 10,017 で頭打ちになる。
 * これを終盤に置くと**その1点だけが突破不能の壁**になる。
 * そのため制限の強い妨害は目標値の低い序盤に置き、
 * 終盤は「伸びを許す」妨害（句の禁止・取得上限）に留める。
 *
 * ## 曲線の形
 *
 * 全段で単調増加。急に跳ねる段を作らない。
 * 各アンティ内は small : big : boss ≒ 1 : 1.5 : 2。
 * 桜井原則の「一直線の坂にしない」に従い、Boss は句の制限で
 * 「攻略を考えさせる難所」にし、目標値の跳ねではなくルールで難しくする。
 *
 * ## 終盤（アンティ7〜8）の目標が接近している理由
 *
 * 1手の理論上限が 13,728 なので、4手でも 54,912 が天井。
 * アンティ8 Boss を 23,000 より上げると勝率が 30% → 7% → 3% と急落する
 * （実測）。終盤は「数値の壁」ではなく「Boss の句制限をどうかわすか」で
 * 難しくする設計なので、目標値の差を小さくしてある。
 */
export const ANTES: AnteConfig[] = [
  { ante: 1, small: 1800, big: 3800, boss: 5000, bossRule: "none" },
  { ante: 2, small: 3600, big: 5100, boss: 6800, bossRule: "zeroOnDuplicate" },
  { ante: 3, small: 5000, big: 8200, boss: 10000, bossRule: "noOrderBy" },
  { ante: 4, small: 7400, big: 10800, boss: 13000, bossRule: "none" },
  { ante: 5, small: 8900, big: 14400, boss: 17000, bossRule: "noLike" },
  { ante: 6, small: 12100, big: 18200, boss: 21000, bossRule: "none" },
  { ante: 7, small: 16300, big: 19000, boss: 22000, bossRule: "noJoin" },
  { ante: 8, small: 22000, big: 22500, boss: 23000, bossRule: "maxRows50" },
];

/** アンティ番号から設定を引く。 */
export function findAnte(ante: number): AnteConfig | undefined {
  return ANTES.find((a) => a.ante === ante);
}

/** アンティとブラインド種別から目標チップを引く。 */
export function targetChips(ante: number, blind: "small" | "big" | "boss"): number {
  const config = findAnte(ante);
  if (!config) throw new Error(`未知のアンティ: ${ante}`);
  return config[blind];
}
